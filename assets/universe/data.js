const MONTHS = { jan:1, feb:2, mar:3, apr:4, may:5, jun:6, jul:7, aug:8, sep:9, oct:10, nov:11, dec:12, summer:6 };
function dateKey(it){
  if (/present/i.test(it.date)) return 1e6;
  const m = (it.date || "").toLowerCase().match(/summer|jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec/);
  return it.year * 100 + (m ? MONTHS[m[0]] : 0);
}
